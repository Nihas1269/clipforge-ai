def _arg(args, option):
    return args[args.index(option) + 1]


def _evaluate(expression: str, t: float) -> float:
    """Evaluate an FFmpeg crop expression (if/lt and arithmetic) at time t."""
    python = expression.replace("if(", "_if(").replace("lt(", "_lt(")
    return eval(  # noqa: S307 - only expressions generated by the code under test
        python,
        {"__builtins__": {}},
        {"_if": lambda c, a, b: a if c else b, "_lt": lambda a, b: a < b, "t": t},
    )


def _crop_option(args, name):
    vf = _arg(args, "-vf")
    crop = vf.split("crop=", 1)[1]
    # Options are separated by unescaped ":"; commas inside are escaped.
    match = re.search(rf"(?:^|:){name}=((?:\\.|[^:,])*)", crop)
    return match.group(1).replace("\\,", ",")


def _nesting_depth(expression: str) -> int:
    depth = deepest = 0
    for char in expression:
        if char == "(":
            depth += 1
            deepest = max(deepest, depth)
        elif char == ")":
            depth -= 1
    return deepest


