@pytest.mark.parametrize("aspect", ASPECTS)
def test_single_keyframe_gives_constant_crop_and_output_size(paths, aspect):
    source, output = paths
    plan = center_crop_plan(1920, 1080, aspect, start=10.0)
    width, height = OUTPUT_RESOLUTIONS[aspect]

    args = build_ffmpeg_args(source, output, start=10.0, end=25.5, plan=plan)

    assert all(isinstance(arg, str) for arg in args)
    # Accurate input seek before -i, then the clip length as output duration.
    assert args.index("-accurate_seek") < args.index("-ss") < args.index("-i")
    assert _arg(args, "-ss") == "10"
    assert _arg(args, "-i") == str(source)
    assert _arg(args, "-protocol_whitelist") == "file"
    assert args.index("-protocol_whitelist") < args.index("-i")
    assert _arg(args, "-t") == "15.5"
    (x, y) = plan.keyframes[0][1:]
    assert _arg(args, "-vf") == (
        f"crop=w={plan.crop_width}:h={plan.crop_height}:x={x}:y={y},"
        f"scale={width}:{height}:flags=lanczos,setsar=1,format=yuv420p"
    )
    assert "ass=" not in _arg(args, "-vf")
    assert width % 2 == 0 and height % 2 == 0
    assert _arg(args, "-c:v") == "libx264"
    assert _arg(args, "-pix_fmt") == "yuv420p"
    assert _arg(args, "-c:a") == "aac"
    assert _arg(args, "-movflags") == "+faststart"
    assert _arg(args, "-f") == "mp4"
    assert args[-1] == str(output)
    assert args[-2] == "-y"


@pytest.mark.parametrize("aspect", ASPECTS)
def test_captions_add_the_ass_filter_after_scaling(paths, tmp_path, aspect):
    source, output = paths
    subtitles = tmp_path / "work dir" / "captions.ass"
