def test_windows_path_is_escaped_for_the_filtergraph():
    escaped = escape_filter_path(r"C:\Temp\it's [x]\captions.ass", windows=True)

    assert escaped == r"C\\:/Temp/it\\\'s \[x\]/captions.ass"


def test_posix_path_is_escaped_for_the_filtergraph():
    escaped = escape_filter_path("/tmp/a:b,c;d/captions.ass", windows=False)

    assert escaped == r"/tmp/a\\:b\,c\;d/captions.ass"


def test_path_with_line_breaks_is_rejected():
    with pytest.raises(ValueError):
        escape_filter_path("/tmp/a\nb.ass", windows=False)


# Output validation


def _info(**overrides):
    values = {
        "duration_seconds": 15.0,
        "width": 1080,
        "height": 1920,
        "fps": 30.0,
        "has_video": True,
        "has_audio": True,
        "video_codec": "h264",
        "audio_codec": "aac",
    }
    values.update(overrides)
    return MediaInfo(**values)


def _check(info, **overrides):
    values = {
        "size_bytes": 1000,
        "width": 1080,
        "height": 1920,
        "duration": 15.0,
        "expect_audio": True,
    }
    values.update(overrides)
    check_render_output(info, **values)


def test_valid_render_passes_within_tolerance():
    _check(_info(duration_seconds=15.0 + DURATION_TOLERANCE_SECONDS - 0.01))
    _check(_info(has_audio=False), expect_audio=False)


@pytest.mark.parametrize(
    ("info", "overrides", "reason"),
    [
        (_info(), {"size_bytes": 0}, "empty"),
        (_info(has_video=False, width=None, height=None), {}, "no_video"),
        (_info(width=1080, height=1080), {}, "wrong_size"),
        (_info(duration_seconds=None), {}, "no_duration"),
        (
            _info(duration_seconds=15.0 + DURATION_TOLERANCE_SECONDS + 0.05),
            {},
            "wrong_duration",
        ),
        (_info(duration_seconds=14.0), {}, "wrong_duration"),
        (_info(has_audio=False), {}, "no_audio"),
    ],
)
def test_invalid_render_is_rejected(info, overrides, reason):
    with pytest.raises(RenderValidationError) as excinfo:
        _check(info, **overrides)

    assert excinfo.value.reason == reason


# Real FFmpeg

_TOOL_SETTINGS = Settings(_env_file=None)


def _render_tools_available() -> bool:
    if not FFMPEG_AVAILABLE:
        return False
    try:
        filters = run_ffmpeg(["-filters"], timeout=30, settings=_TOOL_SETTINGS).stdout
        encoders = run_ffmpeg(["-encoders"], timeout=30, settings=_TOOL_SETTINGS).stdout
    except MediaError:
        return False
    return bool(re.search(rb"\sass\s", filters)) and b"libx264" in encoders


@pytest.fixture(scope="module")
def sample_video(tmp_path_factory):
    if not _render_tools_available():
        pytest.skip(
            SKIP_REASON + " (rendering also needs the libass 'ass' filter and libx264)"
        )
    return make_test_video(tmp_path_factory.mktemp("render") / "sample.mp4")


def _write_captions(path, width, height):
    captions = [
        SimpleNamespace(start_seconds=0.0, end_seconds=0.8, text="Hello {\\b1} world"),
        SimpleNamespace(start_seconds=0.8, end_seconds=2.0, text="Second line"),
    ]
    path.write_text(
        render_ass(captions, default_style("Arial"), width, height),
        encoding="utf-8",
        newline="\n",
    )
    return path


@pytest.mark.parametrize("aspect", ASPECTS)
def test_real_render_has_output_size_and_clip_duration(sample_video, tmp_path, aspect):
    width, height = OUTPUT_RESOLUTIONS[aspect]
    work = tmp_path / "work [1], it's"
    work.mkdir()
    subtitles = _write_captions(work / "captions.ass", width, height)
    output = work / "output.mp4"
    plan = center_crop_plan(TEST_WIDTH, TEST_HEIGHT, aspect, start=0.5)

    run_ffmpeg(
        build_ffmpeg_args(
            sample_video.resolve(),
            output.resolve(),
            start=0.5,
            end=1.5,
            plan=plan,
            subtitles_path=subtitles.resolve(),
        ),
        timeout=120,
        settings=_TOOL_SETTINGS,
    )

    info = probe(output, settings=_TOOL_SETTINGS)
    check_render_output(
        info,
        size_bytes=output.stat().st_size,
        width=width,
        height=height,
        duration=1.0,
        expect_audio=True,
    )
    assert (info.width, info.height) == (width, height)
    assert info.duration_seconds == pytest.approx(1.0, abs=DURATION_TOLERANCE_SECONDS)
    assert info.video_codec == "h264"
    assert info.audio_codec == "aac"


def test_real_render_of_whole_video_with_moving_crop(sample_video, tmp_path):
    crop = TEST_HEIGHT  # 1:1 crop of a 320x240 source is 240x240
    plan = CropPlan(
        TEST_WIDTH,
        TEST_HEIGHT,
        "1:1",
        crop,
        crop,
        (
            Keyframe(0.0, 0, 0),
            Keyframe(1.0, (TEST_WIDTH - crop) // 2, 0),
            Keyframe(2.0, TEST_WIDTH - crop, 0),
        ),
        mode="face",
    )
    output = tmp_path / "moving.mp4"

    run_ffmpeg(
        build_ffmpeg_args(
            sample_video.resolve(), output.resolve(), start=0.0, end=2.0, plan=plan
        ),
        timeout=120,
        settings=_TOOL_SETTINGS,
    )

    info = probe(output, settings=_TOOL_SETTINGS)
    assert (info.width, info.height) == (1080, 1080)
    assert info.duration_seconds == pytest.approx(2.0, abs=DURATION_TOLERANCE_SECONDS)
    assert info.has_audio is True
