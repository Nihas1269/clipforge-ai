def test_multiple_keyframes_give_piecewise_linear_x_in_clip_time(paths):
    source, output = paths
    plan = CropPlan(
        source_width=1920,
        source_height=1080,
        aspect="9:16",
        crop_width=608,
        crop_height=1080,
        keyframes=(
            Keyframe(10.0, 0, 0),
            Keyframe(12.0, 656, 0),
            Keyframe(14.0, 1312, 0),
        ),
        mode="face",
    )

    args = build_ffmpeg_args(source, output, start=10.0, end=20.0, plan=plan)

    expected = "if(lt(t,4),if(lt(t,2),0+(656)*(t-0)/2,656+(656)*(t-2)/2),1312)"
    vf = _arg(args, "-vf")
    # Commas inside the expression are escaped for the filtergraph.
    assert vf.startswith(
        "crop=w=608:h=1080:x=" + expected.replace(",", "\\,") + ":y=0,"
    )
    x = _crop_option(args, "x")
    assert _evaluate(x, 0) == 0
    assert _evaluate(x, 1) == 328
    assert _evaluate(x, 3) == 984
    assert _evaluate(x, 9) == 1312
    # Every position keeps the crop inside the frame.
    assert all(0 <= _evaluate(x, i / 10) <= 1920 - 608 for i in range(0, 101))


def test_keyframes_use_source_time_and_are_clamped_to_the_clip_start(paths):
    source, output = paths
    plan = CropPlan(
        source_width=1920,
        source_height=1080,
        aspect="9:16",
        crop_width=608,
        crop_height=1080,
        keyframes=(
            Keyframe(0.0, 100, 0),
            Keyframe(5.0, 200, 0),
            Keyframe(20.0, 300, 0),
            Keyframe(50.0, 900, 0),
            Keyframe(60.0, 1000, 0),
        ),
        mode="face",
    )

    args = build_ffmpeg_args(source, output, start=10.0, end=30.0, plan=plan)

    x = _crop_option(args, "x")
    # The keyframe at 5 s (before the clip) is the position at clip time 0.
    assert _evaluate(x, 0) == 200
    assert _evaluate(x, 10) == 300
    # Keyframes after the first one past the clip end are not used.
    assert "1000" not in x
    assert _evaluate(x, 19.9) < 900


def test_vertical_movement_gives_a_y_expression(paths):
    source, output = paths
    plan = CropPlan(
        source_width=1080,
        source_height=1920,
        aspect="1:1",
        crop_width=1080,
        crop_height=1080,
        keyframes=(Keyframe(0.0, 0, 0), Keyframe(4.0, 0, 840)),
        mode="face",
    )

    args = build_ffmpeg_args(source, output, start=0.0, end=8.0, plan=plan)

    assert _crop_option(args, "x") == "0"
    y = _crop_option(args, "y")
    assert _evaluate(y, 2) == 420
    assert _evaluate(y, 6) == 840


def test_many_keyframes_are_bounded(paths):
    source, output = paths
    keyframes = tuple(Keyframe(i * 0.5, (i * 37) % 1312, 0) for i in range(2000))
    plan = CropPlan(1920, 1080, "9:16", 608, 1080, keyframes, mode="face")

    args = build_ffmpeg_args(source, output, start=0.0, end=1000.0, plan=plan)

    x = _crop_option(args, "x")
    assert x.count("if(") <= MAX_CROP_KEYFRAMES
    # FFmpeg's expression parser refuses about 100 nested levels.
    assert _nesting_depth(x) < 30
    assert all(0 <= _evaluate(x, t) <= 1312 for t in (0, 1.3, 250, 999.9))


