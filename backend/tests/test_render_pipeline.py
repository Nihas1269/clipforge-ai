def test_output_size_limit_adds_fs(paths):
    source, output = paths
    plan = center_crop_plan(1920, 1080, "9:16")

    assert "-fs" not in build_ffmpeg_args(source, output, start=0, end=1, plan=plan)
    args = build_ffmpeg_args(
        source, output, start=0, end=1, plan=plan, max_output_bytes=1048576
    )
    assert _arg(args, "-fs") == "1048576"
    # An output option, before the output path.
    assert args.index("-i") < args.index("-fs") < len(args) - 1
    for invalid in (0, -1, True, 1.5):
        with pytest.raises(ValueError):
            build_ffmpeg_args(
                source, output, start=0, end=1, plan=plan, max_output_bytes=invalid
            )


def test_relative_paths_and_unknown_aspects_are_rejected(paths):
    source, output = paths
    plan = center_crop_plan(1920, 1080, "9:16")

    with pytest.raises(ValueError):
        build_ffmpeg_args("-i evil.mp4", output, start=0, end=1, plan=plan)
    with pytest.raises(ValueError):
        build_ffmpeg_args(source, "out.mp4", start=0, end=1, plan=plan)
    with pytest.raises(ValueError):
        build_ffmpeg_args(
            source, output, start=0, end=1, plan=plan, subtitles_path="captions.ass"
        )
    with pytest.raises(ValueError):
        build_ffmpeg_args(source, source, start=0, end=1, plan=plan)
    odd = CropPlan(1920, 1080, "3:2", 1620, 1080, (Keyframe(0.0, 0, 0),))
    with pytest.raises(ValueError):
        build_ffmpeg_args(source, output, start=0, end=1, plan=odd)
    with pytest.raises(ValueError):
        output_resolution("2:1")


